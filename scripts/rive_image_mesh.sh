#!/usr/bin/env bash
# RIVE-RIG-002: bind a synthetic RGBA image to a genuine Rive skinned Mesh.
# No editor or hand-painted weights; this fixture uses *known explicit* weights
# to test the RML Image+Mesh data path before automated estimation.
set -u
set -o pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${EVIDENCE_DIR_002:-$ROOT/out/rive-rig-002}"
mkdir -p "$OUT/work" "$OUT/logs" "$OUT/screenshots"
cd "$OUT/work"

python3 - <<'PY'
from pathlib import Path
import base64,math,struct,subprocess,xml.etree.ElementTree as ET,zlib

def png(path):
    # Transparent checker/striped arm image entirely generated by this script.
    w,h=200,44
    raw=bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            skin=(201+(x//12)%2*18, 145+(x//18)%2*12, 111+(y//11)%2*12, 255)
            raw+=bytes(skin)
    def chunk(k,d):
        return struct.pack('>I',len(d))+k+d+struct.pack('>I',zlib.crc32(k+d)&0xffffffff)
    ihdr=struct.pack('>IIBBBBB',w,h,8,6,0,0,0)
    path.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',ihdr)+chunk(b'IDAT',zlib.compress(raw,9))+chunk(b'IEND',b''))

# 6 vertices, four triangles. Index bytes as documented by 'rive docs rigging'.
indices=[0,1,4,0,4,3,1,2,5,1,5,4]
triangles=base64.b64encode(bytes(indices)).decode('ascii')
vertices=[
 ('-100','-22','0','0','255','1'),
 ('0','-22','0.5','0','32640','513'),
 ('100','-22','1','0','255','2'),
 ('-100','22','0','1','255','1'),
 ('0','22','0.5','1','32640','513'),
 ('100','22','1','1','255','2'),
]
for degrees in (0,45,90,135):
    project=Path(f'arm_image_{degrees:03d}')
    subprocess.run(['rive','create',str(project)],check=True,capture_output=True,text=True)
    png(project/'arm.png')
    r=math.radians(degrees)
    file=project/'scene.rml'
    tree=ET.parse(file)
    root=tree.getroot()
    board=next((e for e in root.iter() if e.tag=='Artboard'),None)
    if board is None: raise RuntimeError('no scaffold Artboard')
    board.set('width','480');board.set('height','320');board.set('name','ImageMeshArm')

    # file= is RML's official asset source; assetId must refer to this ImageAsset.
    ET.SubElement(root,'ImageAsset',{'file':'arm.png','id':'0:60','name':'GeneratedArm'})
    node=ET.SubElement(board,'Node',{'x':'230','y':'155','name':'RigSpace'})
    upper=ET.SubElement(node,'RootBone',{'x':'-100','y':'0','length':'100','rotation':'0','id':'0:40','name':'Upper'})
    ET.SubElement(upper,'Bone',{'length':'100','rotation':f'{r:.8f}','id':'0:41','name':'Fore'})
    img=ET.SubElement(node,'Image',{'x':'0','y':'0','assetId':'0:60','name':'SkinnedArm','id':'0:20'})
    mesh=ET.SubElement(img,'Mesh',{'triangleIndexBytes':triangles,'name':'Mesh','id':'0:21'})
    for i,(x,y,u,v,value,index) in enumerate(vertices):
        vertex=ET.SubElement(mesh,'ContourMeshVertex',{'x':x,'y':y,'u':u,'v':v,'name':f'V{i}'})
        ET.SubElement(vertex,'Weight',{'values':value,'indices':index})
    skin=ET.SubElement(mesh,'Skin',{'tx':'0','ty':'0','name':'Skin'})
    ET.SubElement(skin,'Tendon',{'boneId':'0:40','tx':'-100','ty':'0','name':'Upper'})
    ET.SubElement(skin,'Tendon',{'boneId':'0:41','tx':'0','ty':'0','name':'Fore'})
    tree.write(file,encoding='unicode',xml_declaration=False)
PY

probe() {
  local name="$1"; shift
  "$@" > "$OUT/logs/${name}.log" 2>&1
  local rc=$?
  printf '%s\n' "$rc" > "$OUT/logs/${name}.exit"
  echo "== $name ($rc) =="
  sed -n '1,28p' "$OUT/logs/${name}.log"
}
for deg in 000 045 090 135; do
  name="arm_image_$deg"
  probe "verify_$deg" rive "$name" --verify
  probe "build_$deg" rive "$name" --once
  probe "inspect_$deg" rive inspect "$name" --summary
  probe "screenshot_$deg" rive "$name" --screenshot="$OUT/screenshots/weighted_arm_$deg.png" --viewport=480x320 --advance=0s
done

python3 - "$OUT" <<'PY'
from pathlib import Path
import json,sys
d=Path(sys.argv[1]);results={}
for deg in ('000','045','090','135'):
    results[deg]={}
    for k in ('verify','build','inspect','screenshot'):
        p=d/'logs'/f'{k}_{deg}.exit'
        results[deg][k]=int(p.read_text()) if p.exists() else 999
    log=(d/'logs'/f'inspect_{deg}.log').read_text()
    try:
        summary=json.loads(log)
        results[deg]['types']=summary['artboards'][0]['types']
        results[deg]['problems']=summary['problems']
    except Exception as e:
        results[deg]['inspect_error']=str(e)
(d/'image-mesh-result.json').write_text(json.dumps(results,indent=2)+'\n')
print(json.dumps(results,indent=2))
PY

# CLI schema/asset/drawable check is independent of raster visual validation.
for deg in 000 045 090 135; do
  for stage in verify build inspect screenshot; do
    [ "$(cat "$OUT/logs/${stage}_${deg}.exit")" = 0 ] || exit 1
  done
done
python3 "$ROOT/scripts/assert_pose_pixels.py" "$OUT/screenshots"
