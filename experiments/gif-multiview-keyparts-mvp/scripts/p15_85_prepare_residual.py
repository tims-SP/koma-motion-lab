#!/usr/bin/env python3
"""Repair P15-84 missed source eyelash: a bounded semantic exclusion,
not widening the brow/forehead inpaint or changing any foreground layer."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageChops
import hashlib,json
R=Path(__file__).resolve().parents[1];P=R/'private-assets/exports';D=P/'p15-85-outer-eye-seam';D.mkdir(parents=True,exist_ok=True)
srcp=P/'p15-84-clean-brow-inpaint/clean-hidden-face.png'
src=Image.open(srcp).convert('RGBA')
old_mask=Image.open(P/'p15-84-clean-brow-inpaint/mask-full.png').convert('L')
sam=Image.open(P/'p15-81-image-layered/sam3-027-aligned-alpha.png').convert('L')
# This specific 9px stationary stroke was seen *with both eye and SAM3 hair
# hidden*. It belongs to excluded original eyelash, not front bangs.
# Limit to the false-owned source eyelash near the outer-left eye.
poly=[(516,445),(522,442),(528,442),(533,445),(532,455),(519,456),(515,452)]
target=Image.new('L',src.size,0)
ImageDraw.Draw(target).polygon(poly,fill=255)
# Do not touch any region previously regenerated by P15-84.
target=ImageChops.multiply(target,ImageChops.invert(old_mask))
box=(380,300,892,812)
rgb=Image.new('RGBA',src.size,(255,255,255,255));rgb.alpha_composite(src)
rgb.crop(box).convert('RGB').save(D/'input-512.png')
target.crop(box).save(D/'mask-512.png')
target.save(D/'semantic-residual-mask.png')
sha=lambda p:hashlib.sha256(Path(p).read_bytes()).hexdigest()
count=sum(v>0 for v in target.getdata())
q={'schema':'KOMA-P15-85-SOURCE-EYELASH-SEMANTIC-EXCLUSION-V1',
 'sourceUnderpaintSHA256':sha(srcp),'oldMaskSHA256':sha(P/'p15-84-clean-brow-inpaint/mask-full.png'),
 'samMaskSHA256':sha(P/'p15-81-image-layered/sam3-027-aligned-alpha.png'),
 'inputSHA256':sha(D/'input-512.png'),'maskSHA256':sha(D/'mask-512.png'),
 'maskPixelCount':count,'rawResidualPolygon':poly,
 'maskBBox':list(target.getbbox()),'oldMaskOverlapPixels':sum(a>0 and b>0 for a,b in zip(target.getdata(),old_mask.getdata())),
 'method':'LaMa correction only of false hair-owned stationary original eyelash, against P15-84 generated clean hidden face',
 'status':'PREPARED','formalArtMeshAccepted':False,'formalKeyframeAccepted':False}
(R/'evidence/p15-85-qa.json').write_text(json.dumps(q,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(q,ensure_ascii=False),flush=True)
