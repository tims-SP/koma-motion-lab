#!/usr/bin/env python3
"""P15-36 registered local Qwen eye/socket and fringe RGB repaint.

Uses an actual newly model-painted source for each target view; only a small
eye/socket ROI is transferred into 13 semantic RGBA roles. A donor's global
pose mismatch does not authorize global keyview admission. Aligned donor ink,
skin and fringe are separated into layered alpha candidates, and original
P15-35 hidden far-eye underpaint stays available unchanged.
"""
from __future__ import annotations
import hashlib,json
from pathlib import Path
import cv2
import numpy as np
from PIL import Image
from p15_32_mesh_vdd import R,P,slug,read,write,over
from p15_35_depth_mount import ROLES

SRC=P/"p15-35-occlusion-mount"
DONOR=P/"p15-36-painting-candidates/generated"
OUT=P/"p15-36-qwen-local-paint"
QA=R/"evidence/p15-36-qwen-local-repair-qa.json"
N=1024;NATIVE=443

INPUTS=[
 {"yaw":57.5,"file":"yaw057p5-dual-source-qwen.png",
  "sha256":"aWILL_BE_OBSERVED", "iris":[697.4,487.8]},
 {"yaw":60.0,"file":"yaw060-pose-retouch-qwen.png",
  "sha256":"3c37a6e4f11b8c1a2ef33f6e44362088b0a37eb264171c79ff1eab771770da33",
  "iris":[714.9,478.4]},
]

def sha(path):
 return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def readrgb(p):
 return np.asarray(Image.open(p).convert("RGB"))

def soften(a,sigma=3.5):
 return cv2.GaussianBlur(a.astype(np.float32),(0,0),sigma)

def ellipse_roi(cx,cy,rx=68,ry=69):
 yy,xx=np.mgrid[0:N,0:N]
 dist=((xx-cx)/rx)**2+((yy-cy)/ry)**2
 return soften(np.uint8(dist<=1)*255,sigma=11.0)/255.

def align_source(rgb,dx,dy):
 return cv2.warpAffine(rgb,np.float32([[1,0,dx],[0,1,dy]]),(N,N),
      flags=cv2.INTER_CUBIC,borderMode=cv2.BORDER_CONSTANT,
      borderValue=(255,255,255))

def topaint(rgb,mask):
 a=np.zeros((N,N,4),np.uint8)
 a[:,:,:3]=rgb
 a[:,:,3]=np.uint8(np.clip(np.rint(mask*255),0,255))
 return np.asarray(Image.fromarray(a,"RGBA").resize((NATIVE,NATIVE),Image.Resampling.LANCZOS))

def make():
 cam=json.loads((R/"evidence/p15-12-camera-proxy-qa.json").read_text())
 parent=json.loads((R/"evidence/p15-35-occlusion-mount-qa.json").read_text())
 if cam["characterId"]!=parent["characterId"] or parent["characterId"]!="p0_character_001":
  raise AssertionError("P0 target changed")
 frames=[]
 for item in INPUTS:
  yaw=item["yaw"];frame=next(x for x in cam["frames"] if x["yaw"]==yaw)
  k=slug(yaw);folder=OUT/k;folder.mkdir(parents=True,exist_ok=True)
  source=DONOR/item["file"]
  if not source.is_file():raise FileNotFoundError(source)
  digest=sha(source)
  if item["sha256"]!="aWILL_BE_OBSERVED" and digest!=item["sha256"]:
   raise AssertionError("Donor generated bytes changed")
  original=readrgb(source)
  target=np.array(frame["anchors"]["eye.far.iris"]["xy"],np.float32)
  center=np.array(item["iris"],np.float32)
  dx,dy=(target-center).tolist()
  if abs(dx)>30 or abs(dy)>30:raise AssertionError("Donor eye position too far from target")
  registered=align_source(original,dx,dy)
  Image.fromarray(registered,"RGB").save(folder/"donor-eye-registered.png")
  roi=ellipse_roi(float(target[0]),float(target[1]))
  # A feathered subset of the original Qwen RGB is converted into
  # provenance-labelled semantic layers; no independently painted hidden
  # pixels are claimed.
  r=registered[:,:,0].astype(np.int16)
  g=registered[:,:,1].astype(np.int16)
  b=registered[:,:,2].astype(np.int16)
  pink=(b-g>8)&(g<206)&(r>133)&(r>b-9)
  skin=(r>190)&(g>146)&(b>125)&(~pink)
  yy,xx=np.mgrid[0:N,0:N]
  ex=((xx-target[0])/39.0)**2+((yy-target[1])/28.0)**2
  eye_weight=soften(np.uint8(ex<1)*255,5)/255.
  # Interpolate donor geometry only INSIDE eye/socket ROI: eye patch
  # owns the pupil, lids and immediate painted skin surround.
  eye_mask=np.clip(roi*eye_weight,0,1)
  outer=np.clip(roi*(1-eye_weight),0,1)
  hair_mask=outer*soften(pink.astype(np.float32),2.6)
  skin_mask=outer*soften(skin.astype(np.float32),2.6)
  # The donor's eyelashes take precedence even at a hair boundary.
  patches={"eye.far":topaint(registered,eye_mask),
           "face.skin":topaint(registered,skin_mask),
           "hair.front":topaint(registered,hair_mask)}
  roles={role:read(SRC/k/(role+".png")) for role in ROLES}
  painted={}
  for role,patch in patches.items():
   f=folder/(role+".donor-paint.png");write(f,patch)
   base=roles[role]
   new=patch if role=="eye.far" else over(base,patch)
   roles[role]=new
   write(folder/(role+".png"),new)
   painted[role]={"sourceMethod":"QWEN_NEW_RGB_REGISTERED_ROI",
     "sourceFullGeneratedSHA256":digest,
     "donorPaintPath":str(f.relative_to(P)),"donorPaintSHA256":sha(f),
     "visibleDonorAlphaPixels":int((patch[:,:,3]>16).sum()),
     "targetOutputSHA256":sha(folder/(role+".png")),
     "sourceRoleSHA256":sha(SRC/k/(role+".png")),
     "changedPixels":int(np.count_nonzero(np.any(new!=base,axis=2))),
     "hiddenUnderpaintIndependentlyPainted":False}
  for role in ROLES:
   if role not in patches:
    (folder/(role+".png")).write_bytes((SRC/k/(role+".png")).read_bytes())
  for key,srcname in [("eye.far.original-underpaint.png","eye.far.original.png"),
                       ("eye.far.hidden-original.png","eye.far.hidden-underpaint.png")]:
   (folder/key).write_bytes((SRC/k/srcname).read_bytes())
  comp=np.zeros((NATIVE,NATIVE,4),np.uint8)
  for role in ROLES:comp=over(comp,roles[role])
  write(folder/"composite-native.png",comp)
  Image.fromarray(comp,"RGBA").resize((N,N),Image.Resampling.LANCZOS).save(folder/"composite.png")
  baseline=np.asarray(Image.open(SRC/k/"composite.png").convert("RGBA"))
  render=np.asarray(Image.open(folder/"composite.png").convert("RGBA"))
  frames.append({"yaw":yaw,"donor":str(source.relative_to(P)),"donorSHA256":digest,
    "donorAngleSourceAcceptedAsKeyview":False,
    "donorFarIris":item["iris"],"expectedP5FarIris":target.tolist(),
    "registrationOffset":[round(dx,3),round(dy,3)],
    "patchCenter1024":target.tolist(),"patchRadii":[68,69],
    "newPaintedRGBSourcePixels":int((roi>.1).sum()),
    "roleCount":len(ROLES),"newPaintedSemanticRoles":list(patches),
    "partDetails":painted,
    "oldCompositeSHA256":sha(SRC/k/"composite.png"),
    "compositeSHA256":sha(folder/"composite.png"),
    "changedCompositePixels":int(np.count_nonzero(np.any(render!=baseline,axis=2))),
    "artisticallyAccepted":False})
 report={"schema":"KOMA-P15-36-LOCAL-QWEN-PAINT-REPAIR-V1",
  "characterId":"p0_character_001","sourceP15_35QA_SHA256":sha(R/"evidence/p15-35-occlusion-mount-qa.json"),
  "angles":[x["yaw"] for x in frames],"frames":frames,
  "semanticRoleCount":len(ROLES),"newModelPaintedROIRoles":["eye.far","face.skin","hair.front"],
  "independentlyPaintedHiddenUnderpaintCount":0,
  "modelFullImagePoseApproved":False,"fullKeyviewArtAccepted":False,
  "sourceP0HeroIdentityHashVerified":False,
  "productionVddModified":False,
  "status":"TWO_NEW_LOCAL_MODEL_PAINTINGS_SEMANTICALLY_PARTITIONED_FOR_REVIEW"}
 QA.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n")
 print(json.dumps({"status":report["status"],"angles":report["angles"],
  "registeredOffsets":[x["registrationOffset"] for x in frames],
  "changedPixels":[x["changedCompositePixels"] for x in frames],
  "semanticPaintedRolePixels":[{k:v["visibleDonorAlphaPixels"] for k,v in x["partDetails"].items()} for x in frames]}))
 return report

if __name__=="__main__":make()
